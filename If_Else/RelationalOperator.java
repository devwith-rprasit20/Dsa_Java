package If_Else;

public class RelationalOperator {
    public static void main(String[] args) {
        System.out.println(6 > 7);
        System.out.println(6 < 7);
        System.out.println(6 <= 6);
        System.out.println(6 >= 6);
        System.out.println(6 != 5);
        System.out.println(6 == 6);
        ;
    }

}
